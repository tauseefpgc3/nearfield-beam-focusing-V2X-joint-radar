"""D-034 C2: package the paper's checkpoints for Zenodo (no DeepSense data).

    python scripts/repro/c2_package.py      # -> zenodo_package/ (zips, README.md, SHA256SUMS.txt, manifest.json)

Archives:
  location_nets.zip       checkpoints/phase3: LiDAR (single vehicle), LiDAR (varied-trained),
                          radar and fused nets, H head, lr 1e-3, 20 seeds each (80 files)
  codeword_classifier.zip checkpoints/phase3d: B6 selection grid and the 5 seeds per frequency
  design_selection.zip    checkpoints/phase3: the D-031 design-selection runs (P/H heads, lr 3e-4/1e-3,
                          seed 11) and the pre-fix radar/fused runs (superseded, kept for audit)
  deepsense_lidar_nets/deepsense_lidar_nets.zip
                          checkpoints/phase3c: 60 nets trained on DeepSense 6G scenarios 8/31/36.
                          Weights only, no DeepSense data; kept separate so it can be left out.
"""
import hashlib, json, os, zipfile
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "zenodo_package"); CK = os.path.join(ROOT, "checkpoints")
SEEDS = range(11, 221, 11)


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""): h.update(b)
    return h.hexdigest()


def main():
    os.makedirs(os.path.join(OUT, "deepsense_lidar_nets"), exist_ok=True)
    p3 = sorted(os.listdir(os.path.join(CK, "phase3")))
    main_set = [f"lidar_H_lr0.001_s{s}.pt" for s in SEEDS] + [f"lidar_H_lr0.001_s{s}_var.pt" for s in SEEDS] + \
               [f"radar_H_lr0.001_s{s}_r2.pt" for s in SEEDS] + [f"fused_H_lr0.001_s{s}_r2.pt" for s in SEEDS]
    groups = {"location_nets.zip": [("phase3", f) for f in main_set],
              "design_selection.zip": [("phase3", f) for f in p3 if f.endswith(".pt") and f not in main_set],
              "codeword_classifier.zip": [("phase3d", f) for f in sorted(os.listdir(os.path.join(CK, "phase3d"))) if f.endswith(".pt")],
              "deepsense_lidar_nets/deepsense_lidar_nets.zip": [("phase3c", f) for f in sorted(os.listdir(os.path.join(CK, "phase3c"))) if f.endswith(".pt")]}
    man = {}
    for z, files in groups.items():
        for d, f in files: assert os.path.exists(os.path.join(CK, d, f)), f
        with zipfile.ZipFile(os.path.join(OUT, z), "w", zipfile.ZIP_STORED) as zf:
            for d, f in files: zf.write(os.path.join(CK, d, f), f"checkpoints/{d}/{f}")
        man[z] = dict(files=[f"checkpoints/{d}/{f}" for d, f in files], n=len(files), bytes=os.path.getsize(os.path.join(OUT, z)),
                      sha256=sha(os.path.join(OUT, z)), file_sha256={f"checkpoints/{d}/{f}": sha(os.path.join(CK, d, f)) for d, f in files})
        print(z, len(files), man[z]["bytes"] / 1e6, "MB", flush=True)
    json.dump(man, open(os.path.join(OUT, "manifest.json"), "w"), indent=1)
    with open(os.path.join(OUT, "SHA256SUMS.txt"), "w") as f:
        for z, v in man.items(): f.write(f"{v['sha256']}  {z}\n")
    tot = sum(v["bytes"] for v in man.values())
    open(os.path.join(OUT, "README.md"), "w", encoding="utf8").write(f"""# Checkpoints: sensing-aided near-field beam focusing for THz V2X

Trained weights for the paper's results. Code: the release repository (tag revision-plan-v5 or later).
Unzip at the repository root; files land in `checkpoints/<phase>/`.

| Archive | Files | Contents |
|---|---|---|
| location_nets.zip | {man['location_nets.zip']['n']} | LiDAR net (single vehicle), LiDAR net (varied-trained, suffix _var), radar net and fused net (suffix _r2, fixed radar), H head, lr 1e-3, seeds 11-220 |
| codeword_classifier.zip | {man['codeword_classifier.zip']['n']} | Direct codeword classifiers (D-034 B6): selection grid (seed 11) and 5 seeds per frequency |
| design_selection.zip | {man['design_selection.zip']['n']} | D-031 design-selection runs and superseded pre-fix radar/fused runs (audit only) |
| deepsense_lidar_nets/deepsense_lidar_nets.zip | {man['deepsense_lidar_nets/deepsense_lidar_nets.zip']['n']} | LiDAR beam-prediction nets trained on DeepSense 6G scenarios 8, 31, 36 (seeds 11-220). Weights only; no DeepSense data. Trained on data under the DeepSense 6G licence; check its terms before redistributing this archive. |

Total {tot / 1e9:.2f} GB. Each `.pt` holds `model` (state dict), `args`, `history` and, for location nets, `cin`.
Verify: `sha256sum -c SHA256SUMS.txt`; per-file hashes are in `manifest.json`.
Simulated data are regenerated by the code (scripts/phase2, scripts/phase3); see scripts/repro/run_fresh_clone.sh.
""")
    print("total GB", tot / 1e9)


if __name__ == "__main__":
    main()
