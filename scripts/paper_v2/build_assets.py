class Reg:
    """Every number written to an asset goes through here; the manifest is re-checked by trace_check.py."""
    def __init__(self): self.items, self.cache, self.skipped = [], {}, []

    def has(self, k): return os.path.exists(os.path.join(ROOT, J[k]))

    def get(self, k, path):
        if k not in self.cache: self.cache[k] = json.load(open(os.path.join(ROOT, J[k])))
        v = self.cache[k]
        for p in path: v = v[p]
        return v

    def v(self, target, k, path, fmt="{:.2f}", op=None, path2=None, scale=1.0):
        x = self.get(k, path)
        if op == "half_diff": x = (x - self.get(k, path2)) / 2
        x = x * scale; s = fmt.format(x)
        if s.startswith("-") and float(s) == 0: s = s[1:]
        self.items.append(dict(kind="value", target=target, src=J[k], path=list(path), op=op, path2=path2 and list(path2), scale=scale, fmt=fmt, text=s))
        return s

    def key(self, target, k, path, text):
        self.get(k, path); self.items.append(dict(kind="key", target=target, src=J[k], path=list(path), text=text)); return text

    def ticks(self, target, fig):
        fig.canvas.draw()
        for ax in fig.axes:
            for t in ax.get_xticklabels() + ax.get_yticklabels():
                if t.get_text(): self.items.append(dict(kind="tick", target=target, text=t.get_text()))


